// Generates SAMPLE respondents so the site can be built and tested before
// real answers exist.
//
// These are not survey responses. The dataset this writes is marked
// kind: "sample", and the site shows a banner on every screen while it is in
// use. Nothing generated here may be reported as a finding.
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { mulberry32, shuffle } from "../site/js/ingest/rng.js";
import { buildDataset } from "../site/js/ingest/aggregate.js";
import { ITEMS, FIXES } from "../site/js/ingest/vocab.js";

export const SAMPLE_META = {
  kind: "sample",
  title: "Generated sample data",
  note: "Generated by scripts/make-sample.mjs for development. These are not real responses and must not be reported as findings.",
  source: "scripts/make-sample.mjs",
};

const PRICE_SPAN = { dues: [10, 100], formal: [20, 170], trip: [50, 470] };
const FIX_APPEAL = { open: 1.0, draw: 0.6, sliding: 0.5, pwyc: 0.3, forward: 0.1, request: -1.0 };
const SAID_WEIGHTS = [["busy", 35], ["exam", 25], ["silent", 25], ["plans", 20], ["truth", 12], ["uninterested", 8], ["other", 3]];
const AMOUNT_WEIGHTS = [[0, 25], [1, 10], [2, 20], [3, 15], [5, 20], [10, 10]];
const THRESHOLD_WEIGHTS = [[0, 35], [5, 25], [10, 20], [20, 10], ["most", 10]];
const YEARS = ["First-year", "Sophomore", "Junior", "Senior"];

export function makeSampleRespondents(count = 60, seed = 20261120) {
  const random = mulberry32(seed);
  const clamp = (value, low, high) => Math.min(high, Math.max(low, value));
  const snap = (value, item) => clamp(Math.round(value / item.step) * item.step, 0, item.max);
  const pick = (weighted) => {
    let remaining = random() * weighted.reduce((sum, [, weight]) => sum + weight, 0);
    for (const [value, weight] of weighted) {
      remaining -= weight;
      if (remaining < 0) return value;
    }
    return weighted.at(-1)[0];
  };

  const respondents = [];
  for (let i = 0; i < count; i++) {
    // 0 is the tightest budget, 1 the loosest.
    const ease = random();
    const officer = random() < 0.25;

    const prices = {};
    for (const item of ITEMS) {
      if (random() < 0.07) {
        prices[item.id] = null;
        continue;
      }
      const [low, high] = PRICE_SPAN[item.id];
      const skip = snap(low + (high - low) * clamp(ease + (random() - 0.5) * 0.3, 0, 1), item);
      const stretch = Math.min(skip, snap(skip * (0.45 + random() * 0.35), item));
      prices[item.id] = [stretch, skip];
    }

    let guess = null;
    if (random() >= 0.06) guess = Math.round(officer ? 8 + random() * 22 : 15 + random() * 40);

    let skipped = "never";
    const roll = random();
    if (roll < 0.05) skipped = "preferNot";
    else if (ease < 0.3) skipped = random() < 0.55 ? "several" : "once";
    else if (ease < 0.6) skipped = random() < 0.5 ? "once" : "never";
    else if (random() < 0.1) skipped = "once";

    const said = [];
    if (skipped === "once" || skipped === "several") {
      said.push(pick(SAID_WEIGHTS));
      const second = pick(SAID_WEIGHTS);
      if (random() < 0.35 && second !== said[0]) said.push(second);
    }

    const maxdiff = [];
    if (random() >= 0.08) {
      for (let task = 0; task < 5; task++) {
        const shown = shuffle(FIXES.map((fix) => fix.id), random).slice(0, 4);
        const scored = shown.map((id) => ({ id, value: FIX_APPEAL[id] - Math.log(-Math.log(random() || 1e-9)) * 0.8 }));
        scored.sort((a, b) => b.value - a.value);
        maxdiff.push({ shown, best: scored[0].id, worst: scored.at(-1).id });
      }
    }

    let pledge = null;
    if (random() >= 0.05) {
      const amount = pick(AMOUNT_WEIGHTS);
      pledge = amount === 0 ? [0, 0] : [amount, pick(THRESHOLD_WEIGHTS)];
    }

    respondents.push({ year: YEARS[Math.floor(random() * YEARS.length)], officer, prices, guess, skipped, said, maxdiff, pledge });
  }
  return respondents;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = new URL("../site/data/dataset.json", import.meta.url);
  const dataset = buildDataset(makeSampleRespondents(), SAMPLE_META);
  fs.writeFileSync(out, `${JSON.stringify(dataset)}\n`);
  console.log(`Wrote SAMPLE data (${dataset.meta.n} generated respondents, not real responses) to site/data/dataset.json`);
}
